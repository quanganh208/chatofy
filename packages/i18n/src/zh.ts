/**
 * Simplified Chinese (`zh-CN`).
 *
 * Typed `Messages`, for the same reason as `vi.ts`: a key added to `en.ts` and
 * forgotten here is a compile error, not an English string on a Chinese page.
 *
 * ## The register
 *
 * `docs/design-guidelines.md` § Copy register governs each locale independently.
 * English is the reference for meaning, not for structure. Name the wait, the
 * outcome or the next step; the pipeline vocabulary the rule deleted (识别, 转写,
 * 合成 used as steps the reader watches) does not come back in translation.
 *
 * ## Address and terms
 *
 * The reader is 你 everywhere, not 您: this is a tool used daily, not a bank.
 * One word per concept across the whole file: credits are 点数, AI Context is
 * AI 语境 (never 背景, which already means the caption background), a top-up is
 * 充值 and a plan is 套餐.
 *
 * ## Punctuation and type
 *
 * Full-width punctuation inside Chinese sentences, but no 破折号 (——): the webfont
 * owns U+2014 and draws it as two separate Latin dashes, so a pause is a comma or a
 * colon instead. `Be_Vietnam_Pro` has no CJK
 * glyphs; the sans stack in `globals.css` falls back to the platform's CJK face
 * rather than downloading one.
 *
 * The landing demo lines stay Vietnamese and English here too: they show a
 * Vietnamese speaker answered in English, which is what the product does.
 */
